#!/usr/bin/env python3
"""YouTube Music API helper for Quickshell."""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
import time
import webbrowser
from pathlib import Path

CONFIG_DIR = Path.home() / ".config" / "quickshell" / "ytmusic"
BROWSER_FILE = CONFIG_DIR / "browser.json"
OAUTH_FILE = CONFIG_DIR / "oauth.json"
CLIENT_FILE = CONFIG_DIR / "client.conf"
PENDING_FILE = CONFIG_DIR / "browser-auth-pending.json"
YTM_HOME = "https://music.youtube.com"


def emit(payload: dict) -> None:
    print(json.dumps(payload, ensure_ascii=False), flush=True)


def fail(message: str, code: int = 1) -> None:
    emit({"status": "error", "message": message})
    raise SystemExit(code)


def read_client() -> tuple[str, str] | None:
    if not CLIENT_FILE.is_file():
        return None
    lines = CLIENT_FILE.read_text(encoding="utf-8").splitlines()
    if len(lines) < 2 or not lines[0].strip() or not lines[1].strip():
        return None
    return lines[0].strip(), lines[1].strip()


def extract_chrome_cookie_header() -> str:
    with tempfile.NamedTemporaryFile(suffix=".txt", delete=False) as tmp:
        cookie_path = Path(tmp.name)

    try:
        cookie_path.write_text(
            "# Netscape HTTP Cookie File\n# This file is generated by yt-dlp.  Do not edit.\n\n",
            encoding="utf-8",
        )
        subprocess.run(
            [
                "yt-dlp",
                "--cookies-from-browser",
                "chrome",
                "--cookies",
                cookie_path.as_posix(),
                "--skip-download",
                "--no-warnings",
                "--ignore-errors",
                YTM_HOME,
            ],
            capture_output=True,
            text=True,
            check=False,
        )

        pairs: dict[str, str] = {}
        order: list[str] = []
        for line in cookie_path.read_text(encoding="utf-8").splitlines():
            if not line or line.startswith("#"):
                continue
            parts = line.split("\t")
            if len(parts) != 7:
                continue
            domain, _flag, _path, _secure, _expiry, name, value = parts
            if "youtube" not in domain and "google" not in domain:
                continue
            if name not in pairs:
                order.append(name)
            pairs[name] = value

        if not pairs:
            raise RuntimeError("sign in to YouTube Music in Chrome first")

        return "; ".join(f"{name}={pairs[name]}" for name in order)
    finally:
        cookie_path.unlink(missing_ok=True)


def browser_headers(cookie: str) -> dict[str, str]:
    from ytmusicapi.helpers import get_authorization, sapisid_from_cookie

    sapisid = sapisid_from_cookie(cookie)
    return {
        "accept": "*/*",
        "content-type": "application/json",
        "x-goog-authuser": "0",
        "x-origin": YTM_HOME,
        "cookie": cookie,
        "authorization": get_authorization(f"{sapisid} {YTM_HOME}"),
    }


def verify_auth(yt) -> None:
    yt.get_home()


def _save_browser_session(cookie: str) -> None:
    CONFIG_DIR.mkdir(parents=True, exist_ok=True)
    BROWSER_FILE.write_text(json.dumps(browser_headers(cookie), indent=2), encoding="utf-8")


def _try_browser_auth() -> None:
    cookie = extract_chrome_cookie_header()
    if "__Secure-3PAPISID" not in cookie:
        raise RuntimeError("sign in to YouTube Music in Chrome first")

    _save_browser_session(cookie)
    try:
        verify_auth(load_ytmusic())
    except Exception:
        BROWSER_FILE.unlink(missing_ok=True)
        raise


def load_ytmusic():
    try:
        from ytmusicapi import OAuthCredentials, YTMusic
    except ImportError:
        fail("python-ytmusicapi not installed", 4)

    if BROWSER_FILE.is_file():
        return YTMusic(BROWSER_FILE.as_posix())

    if OAUTH_FILE.is_file():
        client = read_client()
        if client is None:
            fail("oauth token found but client credentials are missing", 3)
        client_id, client_secret = client
        return YTMusic(
            OAUTH_FILE.as_posix(),
            oauth_credentials=OAuthCredentials(client_id, client_secret),
        )

    fail("not authenticated", 3)


def _song_artist(item: dict) -> str:
    artists = item.get("artists") or []
    if not artists:
        return ""
    return ", ".join(a.get("name", "") for a in artists if a.get("name"))


def _track_from_search(item: dict) -> dict | None:
    if item.get("resultType") not in (None, "song", "video"):
        return None
    video_id = item.get("videoId")
    if not video_id:
        return None
    return {
        "videoId": video_id,
        "title": item.get("title") or "",
        "artist": _song_artist(item),
        "duration": item.get("duration") or "",
        "album": (item.get("album") or {}).get("name", ""),
    }


def _track_from_playlist(item: dict) -> dict | None:
    video_id = item.get("videoId") or item.get("setVideoId")
    if not video_id:
        return None
    return {
        "videoId": video_id,
        "title": item.get("title") or "",
        "artist": _song_artist(item),
        "duration": item.get("duration") or "",
        "album": (item.get("album") or {}).get("name", ""),
    }


def search_songs(yt, query: str, limit: int) -> list[dict]:
    results: list[dict] = []
    for item in yt.search(query, filter="songs", limit=limit):
        track = _track_from_search(item)
        if track:
            results.append(track)
        if len(results) >= limit:
            break
    return results


def cmd_status(_: argparse.Namespace) -> None:
    if not BROWSER_FILE.is_file() and not OAUTH_FILE.is_file():
        emit({"status": "noauth"})
        return
    try:
        yt = load_ytmusic()
        verify_auth(yt)
        emit({"status": "authed"})
    except SystemExit:
        raise
    except Exception as exc:  # noqa: BLE001
        emit({"status": "noauth", "message": str(exc)})


def cmd_browser_auth_sync(_: argparse.Namespace) -> None:
    try:
        _try_browser_auth()
    except Exception as exc:  # noqa: BLE001
        emit({"status": "pending", "message": str(exc)})
        return
    PENDING_FILE.unlink(missing_ok=True)
    emit({"status": "ok"})


def cmd_browser_auth_start(_: argparse.Namespace) -> None:
    CONFIG_DIR.mkdir(parents=True, exist_ok=True)
    PENDING_FILE.write_text(json.dumps({"started_at": time.time()}), encoding="utf-8")
    emit({"status": "ok", "browser_opened": webbrowser.open(YTM_HOME)})


def cmd_browser_auth_poll(_: argparse.Namespace) -> None:
    if not PENDING_FILE.is_file():
        fail("no pending browser auth")

    try:
        _try_browser_auth()
    except Exception as exc:  # noqa: BLE001
        emit({"status": "pending", "message": str(exc)})
        return

    PENDING_FILE.unlink(missing_ok=True)
    emit({"status": "ok"})


def cmd_search(args: argparse.Namespace) -> None:
    query = args.query.strip()
    if not query:
        emit({"status": "ok", "results": []})
        return

    yt = load_ytmusic()
    results = search_songs(yt, query, args.limit)
    emit({"status": "ok", "results": results})


def cmd_playlists(args: argparse.Namespace) -> None:
    yt = load_ytmusic()
    playlists = []
    for item in yt.get_library_playlists(limit=args.limit):
        playlist_id = item.get("playlistId")
        if not playlist_id:
            continue
        playlists.append(
            {
                "playlistId": playlist_id,
                "title": item.get("title") or "",
                "count": item.get("count") or "",
                "owned": bool(item.get("owned")),
            }
        )
    emit({"status": "ok", "playlists": playlists})


def cmd_playlist_tracks(args: argparse.Namespace) -> None:
    yt = load_ytmusic()
    playlist = yt.get_playlist(args.playlist_id, limit=args.limit)
    tracks = []
    for item in playlist.get("tracks") or []:
        track = _track_from_playlist(item)
        if track:
            tracks.append(track)
    emit(
        {
            "status": "ok",
            "playlistId": args.playlist_id,
            "title": playlist.get("title") or "",
            "tracks": tracks,
        }
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    sub = parser.add_subparsers(dest="command", required=True)

    sub.add_parser("status")
    sub.add_parser("browser-auth-sync")
    sub.add_parser("browser-auth-start")
    sub.add_parser("browser-auth-poll")

    search = sub.add_parser("search")
    search.add_argument("query")
    search.add_argument("--limit", type=int, default=3)

    playlists = sub.add_parser("playlists")
    playlists.add_argument("--limit", type=int, default=50)

    playlist_tracks = sub.add_parser("playlist-tracks")
    playlist_tracks.add_argument("playlist_id")
    playlist_tracks.add_argument("--limit", type=int, default=200)

    args = parser.parse_args()

    handlers = {
        "status": cmd_status,
        "browser-auth-sync": cmd_browser_auth_sync,
        "browser-auth-start": cmd_browser_auth_start,
        "browser-auth-poll": cmd_browser_auth_poll,
        "search": cmd_search,
        "playlists": cmd_playlists,
        "playlist-tracks": cmd_playlist_tracks,
    }
    handlers[args.command](args)


if __name__ == "__main__":
    main()
